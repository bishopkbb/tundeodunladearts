// Reads the photos in public/Assets/highlights/ and writes src/lib/highlightImages.generated.ts
// (width, height and a tiny blur preview for each one) so the Gallery Highlights page can lay them out
// without layout shift.
//
// Run:  node scripts/generate-highlight-media.mjs
// Re-run it whenever a photo is added to or removed from public/Assets/highlights/.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(root, 'public', 'Assets', 'highlights');
const GENERATED = path.join(root, 'src', 'lib', 'highlightImages.generated.ts');

const files = fs
  .readdirSync(DIR)
  .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  .sort();

const entries = [];
for (const file of files) {
  const input = path.join(DIR, file);
  const meta = await sharp(input).rotate().metadata();
  const upright = meta.orientation && meta.orientation >= 5; // EXIF rotates the picture by 90 degrees
  const width = upright ? meta.height : meta.width;
  const height = upright ? meta.width : meta.height;
  const blur = await sharp(input).rotate().resize(16).blur(1).jpeg({ quality: 50 }).toBuffer();
  const slug = file.replace(/\.[^.]+$/, '');
  entries.push({
    slug,
    src: `/Assets/highlights/${file}`,
    width,
    height,
    blurDataURL: `data:image/jpeg;base64,${blur.toString('base64')}`,
  });
  console.log(`${slug.padEnd(24)} ${width}x${height}`);
}

const body = entries
  .map((e) => `  '${e.slug}': {\n    src: '${e.src}',\n    width: ${e.width},\n    height: ${e.height},\n    blurDataURL: '${e.blurDataURL}',\n  },`)
  .join('\n');

fs.writeFileSync(
  GENERATED,
  `// AUTO-GENERATED by scripts/generate-highlight-media.mjs. Do not edit by hand.\n\nexport interface HighlightImage {\n  src: string;\n  width: number;\n  height: number;\n  blurDataURL: string;\n}\n\nexport const highlightImages = {\n${body}\n} as const satisfies Record<string, HighlightImage>;\n\nexport type HighlightImageKey = keyof typeof highlightImages;\n`
);
console.log(`\n${entries.length} images written to src/lib/highlightImages.generated.ts`);
